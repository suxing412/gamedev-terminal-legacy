// 事流.js — 产线事件怎么归一、怎么折叠。**四处共用同一份。**
//
// 之前这套逻辑存了四份：`server.js` 的 /api/events、`public/app.js` 的右栏、
// `server/routes/监视.js` 的服务端渲染、`public/监视.js` 的前端重渲染。
// 前两份 2026-08-31 晚治好了刷屏，后两份原封不动——同一天的监视页实测：
// 12 行事件去重后只有 5 种，8 行是同一句互保重启对账；
// 唯一那条急件「OAuth 已过期且自续连败（5 发）……这次真该人工登了」
// 只占一行，还被急件包装行与裸行重复渲染了两遍。
//
// **一个概念存四份，就一定会有一天只改了其中两份**（同一天，同一个人，同一个晚上）。
//
// 单独一个文件还有第二个理由：判据要 require 它。
// 它在 public/ 下是为了浏览器拿得到；服务端 require 一个 public/ 下的文件看着别扭，
// 但比"服务端和浏览器各写一份、靠判据比对文本"要诚实得多——那种比对
// 会因为无关的排版差异而红，而那种判据最后一定会被人关掉。

(function (根) {
  'use strict';

  // 事件的「种」。
  //
  // **只抹计数器，不抹别的数字。**首版是 `replace(/\d[\d.,:]*/g,'#')`——把所有数字都归一，
  // 于是 `额度余额=10000` 与 `额度余额=10` 会被判成同一种、折成一行 `×2`：
  // 既看不到余额跌到了 10，也不知道那一行显示的是哪一次的值。
  // 那直接违反 PRODUCT.md 原则五「数字必须是真的」——
  // **一个会因为折叠而悄悄变错的数字，比没有这个数字坏得多。**
  // （异厂评审 2026-08-31 的击杀原文；同一条也解释了为什么
  //   `部署 job=7411 重试=2` 与 `job=7412` 不该被合并。）
  //
  // 所以只归一**形状明确是计数器**的那几个键：seq / 序号 / 次序 / no / id。
  // 归一得少 = 折得少 = 屏上多几行；归一得多 = 悄悄吃掉真值。这两种错的代价不对称。
  const 计数器键 = /\b(seq|序号|次序|no|id)(\s*[=:]\s*)\d+/gi;
  function 事种(文) {
    return String(文 || '').replace(计数器键, '$1$2#').replace(/\s+/g, ' ').trim();
  }

  /**
   * 折叠(条们, 选项) → [{ 时, 文, 次, 起时 }]
   *
   * **连着的同种事件合成一行。**2026-08-31 实测逼出来的：那一刻 /api/events 回 40 条，
   * 去重后只有一种——常驻可见的那一整栏在用 40 行说同一句「还活着」。
   * 而 PRODUCT.md 第一条原则是「状态先于叙述：活着 / 在跑什么 / 谁等我，
   * 三问必须不用滚动、不用点击就能回答」。四十条心跳把「产线刚发生了什么」
   * 这一问的答案埋掉了——**它不是没答，是答案被同一句话刷屏刷没了**。
   *
   * 只折**相邻**的同种，不跨越中间插进来的别的事件：
   * 「心跳×20 → 一次失败 → 心跳×20」要看得出那次失败夹在中间。
   * 全局归并会把时序抹平，而时序正是事件流的全部价值。
   *
   * 入参按**新在前**排列（列表怎么显示就怎么传）。
   * 选项.上限：折完最多留几组，不传则不限。
   */
  function 折叠(条们, 选项) {
    const 上限 = 选项 && Number(选项.上限) > 0 ? Number(选项.上限) : 0;
    const 出 = [];
    for (const e of (条们 || [])) {
      const 种 = 事种(e.文);
      // 上游可能已经折过一轮（服务端在更大的窗口上折）。
      // 那边给的 次 要认下来，不能从 1 重新数——不然服务端折掉的那些就凭空少了。
      const 本次 = Number.isFinite(e.次) && e.次 > 0 ? e.次 : 1;
      const 尾 = 出[出.length - 1];
      if (尾 && 尾.种 === 种) {
        尾.次 += 本次;
        尾.起时 = e.起时 || e.时;        // 新在前，所以后来的那条是更早的
        尾.起日 = e.起日 || e.日 || 尾.起日;
        continue;
      }
      if (上限 && 出.length >= 上限) break;
      出.push({
        种, 时: e.时, 起时: e.起时 || e.时, 文: e.文, 次: 本次, 级: e.级 || null,
        日: e.日 || null, 起日: e.起日 || e.日 || null,
      });
    }
    return 出;
  }

  // ── 监视页那种行格式：`[时间] [来源] 级 标签 | 正文` ──
  //
  // 拆与画都放在这里，是因为监视页有**两处渲染**：首屏由服务端画、之后由前端画，
  // 而 public/监视.js 的头注自己写着「两处画得不一样，人会看到页面在刷新的瞬间跳一下」。
  // 那句话是对的，但靠"两边各抄一份、记得同步"来保证，从来没有保证住过。
  const 行式 = /^\[([^\]]+)\]\s*\[([^\]]+)\]\s*(急|常|守望)?\s*([^|]*)\|?\s*(.*)$/;
  function 拆事(行们) {
    return (行们 || []).map((l) => {
      const m = String(l).match(行式);
      return {
        时: m ? m[1].slice(11, 16) : '',
        级: m ? (m[3] || '常') : '常',
        文: m ? (m[5] || m[4] || '') : String(l),
      };
    });
  }

  const 转 = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

  /**
   * 一个时刻怎么写。
   *
   * **今天的只写 HH:MM，别的日子必须带上 MM-DD。**
   * 窗口是 600 行 ≈ 58 小时，而首版每行只有 HH:MM：实测一屏 51 组里 30 组不是当天，
   * 「03:49 值守塔阵亡」实际是两天前，上下行标着 05:11 与 03:46——
   * **时刻局部递减，屏上没有任何提示**。一栏按时间倒序的流，
   * 如果它的时刻读起来不是单调的，那这一栏就不能信了。
   *
   * 缺日期时只写时刻（老数据、或监视页那种本来就只有当天的源），不编一个日期出来。
   */
  function 刻(日, 时, 今日) {
    if (!日 || (今日 && 日 === 今日)) return String(时 || '');
    return String(日).slice(5) + ' ' + String(时 || '');
  }

  /** 一条（可能是折起来的）事件的 <li>。折起来的要讲清「同一件事、几次、从什么时候到什么时候」。 */
  function 事条(e, 今日) {
    const 计 = e.次 > 1
      ? `<b class="wev-n">×${e.次}</b><span class="wev-s">${转(刻(e.起日, e.起时, 今日))}→${转(刻(e.日, e.时, 今日))}</span>`
      : '';
    return `<li class="wev-i${e.级 === '急' ? ' urg' : ''}${e.次 > 1 ? ' fold' : ''}">`
      + `<time>${转(刻(e.日, e.时, 今日))}</time>`
      + `<span class="txt">${转(String(e.文).slice(0, 110))}</span>${计}</li>`;
  }

  /** 「等着你看的」清单里的一条。同样两处渲染共用一份。 */
  function 等条(e) {
    const 急 = String((e && e.级别) || '') === '急';
    return `<li class="wlist-i${急 ? ' urg' : ''}">`
      + `<time>${转(String((e && e.t) || '').slice(11, 16))}</time>`
      + `<span class="k">${转(String((e && (e.类型 || e.规则)) || '').slice(0, 10))}</span>`
      + `<span class="txt">${转(String((e && (e.摘要 || e.文本)) || '').slice(0, 90))}</span></li>`;
  }

  /** 去掉内部用的 种 字段（下发给前端时不需要它）。 */
  const 脱种 = (组们) => (组们 || []).map((x) => {
    const y = {}; for (const k in x) if (k !== '种') y[k] = x[k];
    return y;
  });

  const api = { 事种, 折叠, 脱种, 拆事, 事条, 等条, 刻 };
  if (typeof module === 'object' && module && module.exports) module.exports = api;
  else 根.事流 = api;
}(typeof self !== 'undefined' ? self : this));
