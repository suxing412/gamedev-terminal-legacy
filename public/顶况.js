// 顶况.js — 顶栏那几个读数怎么写成字。
//
// 单独一个文件，是为了它能被判据 require。顶栏是这块屏上**唯一一处一直在视野里**的
// 地方，它写错一个字，人就会照着错的那个字安排接下来一小时。
//
// 2026-08-31 巡礼实测抓到两条：
//   ① 登录还剩 40 分钟，屏上写「登录 0h」——`Math.floor(40/60)`。
//      整个小于一小时的区间（**也正是唯一要紧的那个区间**）全被压成一个读着像零的数。
//      更难看的是它和横幅对不上：横幅的临期线是 30 分，于是 30–59 分之间，
//      顶栏说「0h」、横幅说「没事」，两个都出自同一份数据。
//   ② 额度只显示周窗口，且把「（09-04 19:00 重置）」整串摆出来——
//      197px，占了整条顶况的 31%，而**当下真正会把你拦住的是 5 小时窗口**，
//      它一个字都没显示。重置时刻只在快撞顶时才是个问题，21% 的时候它是噪音。

(function (根) {
  'use strict';

  // 登录还剩多久。小时是个太粗的刻度：这块屏关心的是「够不够撑完手上这件事」，
  // 而那个尺度以分钟计。所以 90 分钟以下一律说分钟。
  function 登录文(态, 剩余分) {
    if (态 !== '有效') return '登录' + (态 || '读不到');
    // **先判"有没有这个数"，再判它是多少。**
    // Number(null) 是 0、Number('') 也是 0，直接算的话
    // 「没读到剩余分钟」会被写成「登录已过期」——把一个不知道，说成了一个确定的坏消息。
    // PRODUCT 原则五要挡的正是这一步。
    if (剩余分 === null || 剩余分 === undefined || 剩余分 === '') return '登录—';
    const m = Number(剩余分);
    if (!Number.isFinite(m)) return '登录—';
    if (m <= 0) return '登录已过期';
    if (m < 90) return `登录 ${Math.round(m)} 分`;
    const h = m / 60;
    return `登录 ${h < 10 ? h.toFixed(1) : Math.round(h)}h`;
  }

  // 额度。两个窗口都要出现：5 小时窗口决定「这一小时还能不能干活」，
  // 周窗口决定「这一周还能开几张单」——只报后者等于把当下那道闸藏起来。
  //
  // 重置时刻只在**快撞顶时**才是问题。低水位时它是一串没人会用的数字，
  // 却占着顶栏三分之一的宽度。所以给它一条线：任一窗口过线才把重置时刻摆出来。
  const 报重置线 = 70;
  function 额度文(窗们, 线) {
    const 表 = Array.isArray(窗们) ? 窗们 : [];
    if (!表.length) return { 文: '额度—', 详: '' };
    const 阈 = Number.isFinite(线) ? 线 : 报重置线;
    const 短名 = (l) => String(l || '').replace('小时', 'h').replace(/^周$/, '周');
    const 段 = 表.map((w) => `${短名(w.label)} ${w.pct}%`);
    const 详 = 表.map((w) => `${w.label} ${w.pct}%，${w.reset} 重置`).join(' · ');
    const 紧 = 表.filter((w) => Number(w.pct) >= 阈);
    if (紧.length) {
      // 快撞顶的那个（不是两个都摆）——摆两串重置时刻回到原来的宽度问题上去了
      const 最 = 紧.reduce((a, b) => (Number(b.pct) > Number(a.pct) ? b : a));
      return { 文: `额度 ${段.join(' · ')}（${短名(最.label)} ${最.reset} 重置）`, 详, 紧: 最.label };
    }
    return { 文: `额度 ${段.join(' · ')}`, 详, 紧: null };
  }

  // ── 拆栏之后的三格（2026-09-02 顶条第一性 + 对抗性评审）────────────
  //
  // 左右两栏搬走之后，这条 44px 是屏上**唯一一处一直在视野里**的东西，
  // 而 PRODUCT.md 原则一要求「活着 / 在跑什么 / 谁等我」三问不用滚动不用点击就能答。
  // 评审把七格砍到三格，判据是两条：**数据源不可达时也说得出真话**、
  // **不需要第二个数配合就能读**。答不了的进凭幅（要紧时长出一行）或进页面。

  /**
   * 人闸格：`24验收 · 1定夺 · 11解除停靠` ＋ 年龄章 `14天`。
   *
   * **为什么不是「人闸 61」。** 61 对「要不要现在转过来」没有分辨力——
   * 它昨天是 61、上周也是 61；而真正会让人动手的是「这一批是同一个动作，
   * 可以一次处理完」。按动作键分批之后，「24验收」既说了量也说了**要做什么**，
   * 一格顶两格。这也正是左栏 61 个按钮那堵墙的病根（见 闸分组.js 的案由）。
   *
   * 排序按各批最久停摆降序，最多三批，超出的并成 `+N`。
   * 词面 `动作键 || 闸名 || '待裁'`——上游 /api/attn 里 G13/G14/G25/G24 的
   * 动作键**实测是 null**，写成 `b.动作键 + 词` 会在屏上渲染出 `1null`。
   *
   * 档位不在这里定阈值：调用方把 闸分组.js 的 久档 传进来，**一把尺子**。
   */
  function 人闸文(批们, 阈, 久档) {
    if (!Array.isArray(批们)) return { 文: '人闸 读不到', 章: null, 档: 0, 读不到: true };
    const 表 = 批们.filter((b) => b && Number(b.n) > 0);
    if (!表.length) return { 文: '没有等你的', 章: null, 档: 0, 最久小时: 0 };
    const 序 = 表.slice().sort((a, b) => (Number(b.最久小时) || 0) - (Number(a.最久小时) || 0));
    const 词 = (b) => (String(b.动作键 || b.闸名 || '').trim() || '待裁');
    const 余 = 序.slice(3).reduce((s, b) => s + (Number(b.n) || 0), 0);
    // **结构一并交出去**，让画的人不用拿正则去拆自己刚拼好的那句话。
    // 数字要染琥珀、动词染 ink-2、分隔点染 ink-3——从串上再解析一遍，
    // 就是把同一个决定放在两处，而其中一处没有判据看着（守③c 盯的正是这类）。
    const 词组 = 序.slice(0, 3).map((b) => ({ n: Number(b.n), 词: 词(b) }));
    const 文 = 词组.map((x) => `${x.n}${x.词}`).join(' · ') + (余 ? ` +${余}` : '');
    const 最久 = 序.reduce((m, b) => Math.max(m, Number(b.最久小时) || 0), 0);
    const 天 = Math.floor(最久 / 24);
    return {
      文,
      词组,
      余,
      章: 天 >= 1 ? `${天}天` : null,
      档: typeof 久档 === 'function' ? 久档(最久, 阈) : 0,
      最久小时: 最久,
    };
  }

  // 跑龄的写法。**与 app.js 的 跑了() 同一把尺**（那边改成调这里）——
  // 顶条说「最久 42′」而跑列说别的，是同一份数据两种说法，本文件开头那两桩案都是这么来的。
  const 卡线分 = 180;          // 来自 journal 派发时自己写的「超时闸 180m 派发时快照」
  function 龄文(分) {
    const m = Math.max(0, Math.floor(Number(分) || 0));
    return m < 60 ? m + '′' : Math.floor(m / 60) + '° ' + (m % 60) + '′';
  }

  /**
   * 产线格：六态判别。
   *
   * **「在跑 N」这个量本身选错了**，所以整格换掉：
   * N=0 时它误报安静（干完了 和 派单器死了 长得一样），
   * N>0 时它误报正常（journal 实证：codex 钉死冻结池致静默滞留 7h，
   * 那七小时里屏上一直写着「在跑 N」）。改成状态判别 + 最久跑龄。
   *
   * 第五态 `零在跑 · 全卡在你` 是三版提案都漏的那一格：
   * 没在跑、没待派、没在途，而闸上还压着东西——**产线不是闲，是在等你**。
   *
   * 不报「停了多久」：/api/events 只读当月（server.js:357-358），
   * 实测 journal/2026-09.log 里 `实弹开工` 零条，这个数今天取不到；
   * 就算补上，每月 1 号 00:04 它会读成「停 0.0 天」。
   */
  function 产线文(况, 现在) {
    const s = 况 || {};
    const 今 = Number.isFinite(现在) ? 现在 : Date.now();
    if (s.读不到 || !Array.isArray(s.在跑)) return { 文: '产线 读不到', 级: '警' };
    const n = s.在跑.length;
    const 待 = (Number(s.待派) || 0) + (Number(s.在途) || 0);
    const 闸 = Number(s.闸数) || 0;
    if (n > 0) {
      let 最 = -1; let 谁 = '';
      for (const x of s.在跑) {
        const t = Date.parse((x && x.起时) || '');
        if (Number.isNaN(t)) continue;
        const m = Math.floor((今 - t) / 60000);
        if (m > 最) { 最 = m; 谁 = String((x && (x.单号 || x.号 || x.名)) || '').trim(); }
      }
      if (最 < 0) return { 文: `在跑 ${n}`, 级: '常' };          // 有单但读不出起时：不编一个龄
      if (最 >= 卡线分) return { 文: `在跑 ${n} · ${谁 ? 谁 + ' ' : ''}卡 ${龄文(最)}`, 级: '警' };
      return { 文: `在跑 ${n} · 最久 ${龄文(最)}`, 级: '常' };
    }
    // **不写「待派 N」。** 这个 N 是 待派+待重派+已排期+在途+初检+核查+仲裁 的和，
    // 而「待派」在监制台是其中一个具体状态——屏上写「待派 12」而台账里待派是 11，
    // 就是拿一个标签盖住另一个数。这块屏的全部可信度建立在「数字必须是真的」上
    // （PRODUCT 原则五），一个盖错的标签比少一格贵得多。
    // 「待跑」才是这个和的准确名字：在管线里、但此刻没有会话在跑。
    if (待 > 0) return { 文: `零在跑 · 待跑 ${待}`, 级: '警' };
    if (闸 > 0) return { 文: '零在跑 · 全卡在你', 级: '警' };
    return { 文: '产线空闲', 级: '弱' };
  }

  const api = { 登录文, 额度文, 报重置线, 人闸文, 产线文, 龄文, 卡线分 };
  if (typeof module === 'object' && module && module.exports) module.exports = api;
  else 根.顶况 = api;
}(typeof self !== 'undefined' ? self : this));
