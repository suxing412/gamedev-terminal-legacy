// 写手闸.js — 拦住坐席去写「制作人正锁着的文件」（PreToolUse）
//
// ── 为什么会有这个文件 ────────────────────────────────────────────
// 2026-08-31 验收复核 grep 出来：lib/文锁.js 的 外部可写() 写好了、判据齐了，
// **但生产代码零调用点**——只有定义、两句声称它是硬闸的注释、和两个直接调它的判据。
// 而告示对坐席说的是「硬拦在 server 侧，写了也会被拒」。
// **判据全绿，因为判据自己直接调那个函数。**这正是 H104 要防的假判据。
//
// 现在把它接上。接法上有个选择，选了后者：
//   甲｜往 ~/.claude/settings.json 加 PreToolUse —— 改制作人的全局配置，
//      而且会作用到**所有** claude 会话，包括跟文稿台毫无关系的那些
//   乙｜SDK 的 options.hooks —— 只作用于终端拉起的坐席，随进程生死，不留全局残留
// 乙 更小、更准，也不需要制作人的机器配置发生任何改变。
//
// ── 判定口径 ──────────────────────────────────────────────────
// **只拦写，不拦读。**坐席读锁着的文件是正当的（它得知道那里写着什么才能答话）；
// 拦的是「在制作人手底下把文件改了」。
// 拦下来之后要**记一条解锁请求**——不能让坐席干等，也不能让制作人看不见有人在等。
'use strict';

// 会落盘的工具。MultiEdit 现在的 SDK 里未必有，列上不吃亏：多一个名字不会误伤。
const 写工具 = new Set(['Edit', 'Write', 'NotebookEdit', 'MultiEdit']);

/**
 * 取路径(工具名, 工具入) → [绝对路…]
 * 不同工具把路径放在不同字段里；**取不到就返回空数组，让上层放行**——
 * 一个认不出的工具不该被当成写操作拦住（那会让坐席莫名其妙地做不了事）。
 */
function 取路径(工具名, 入) {
  if (!入 || typeof 入 !== 'object') return [];
  const 出 = [];
  const 推 = (v) => { if (typeof v === 'string' && v.trim()) 出.push(v); };
  推(入.file_path);
  推(入.notebook_path);
  推(入.path);
  // MultiEdit 风格：edits: [{ file_path }]
  if (Array.isArray(入.edits)) for (const e of 入.edits) if (e) 推(e.file_path);
  return 出;
}

/**
 * 判写(工具名, 工具入, 查锁) → { 决: 'allow' | 'deny', 因, 挡住的: [路…] }
 *
 * 查锁(绝对路) → { 行: boolean, 因, 键? }，就是 文锁.js 的 外部可写()。
 *
 * **查锁抛异常时放行。**理由：这道闸的作用是防止误伤制作人正在改的东西，
 * 而它自己坏掉不该把坐席的全部写操作变成不可用——那是把一个小概率的碰撞
 * 换成一个大概率的瘫痪。锁文件读不出来时，告示那条软约定仍在。
 */
function 判写(工具名, 工具入, 查锁) {
  if (!写工具.has(String(工具名))) return { 决: 'allow', 因: '不是写工具', 挡住的: [] };
  const 路们 = 取路径(工具名, 工具入);
  if (!路们.length) return { 决: 'allow', 因: '取不到路径', 挡住的: [] };

  const 挡 = [];
  for (const p of 路们) {
    let r;
    try { r = 查锁(p); } catch (e) { continue; }   // 闸自己坏了不拖垮坐席
    if (r && r.行 === false) 挡.push({ 路: p, 因: r.因 || '被锁着', 键: r.键 });
  }
  if (!挡.length) return { 决: 'allow', 因: '没有人锁着', 挡住的: [] };

  return {
    决: 'deny',
    挡住的: 挡,
    // 拒绝理由要**能让坐席知道下一步该干什么**，不是只说「不行」。
    因: `这份文件正被制作人在文稿台里编辑，写入已被拦下：\n`
      + 挡.map((x) => `  · ${x.路}（${x.因}）`).join('\n')
      + `\n\n**不要绕开它**（比如改用 Bash 写、或换个路径写法）。`
      + `\n请改成：在回话里说清楚你想改哪几行、改成什么，由制作人落笔；`
      + `\n或者等他解锁——你的请求已经进了他屏上的人闸队列。`,
  };
}

module.exports = { 判写, 取路径, 写工具 };
