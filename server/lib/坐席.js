// 本期只接助理与总监两席模型；其余席位先登记，避免界面、@ 路由与调用层各自维护一份名单。
const 全部 = Object.freeze([
  Object.freeze({ 名: '助理', 接模型: true, 人设: '协调各主管，把此刻该看的事实呈给制作人。' }),
  Object.freeze({ 名: '总监', 接模型: true, 人设: '从项目全局给出判断与建议，但不直接改台账。' }),
  Object.freeze({ 名: '终端项管', 接模型: false, 人设: '汇总跨项目进度与风险，只看不改排程。' }),
  Object.freeze({ 名: '情报主管', 接模型: false, 人设: '整理技术、工具与行业情报，供决策时查阅。' }),
  Object.freeze({ 名: '财务', 接模型: false, 人设: '跟踪额度、时间与返工成本，提示资源风险。' }),
  Object.freeze({ 名: '市场', 接模型: false, 人设: '基于情报分析市场与玩家，不替制作人作产品判断。' }),
  Object.freeze({ 名: '营销', 接模型: false, 人设: '筹备同行、曝光与发售路线建议，执行仍由制作人决定。' }),
]);

// ── 自定义席位（2026-09-02 批六，制作人拍板）─────────────────────
//
// 内建那七席写死在上面；自定义席位**一席一份协议文档**，扫 `席位/*.md` 得来
// （见 server/lib/席位档.js）。制作人的话：「智能体协议就按照文档库里的，
// 可以直接在自定义中跳转到文档库中开编辑器进行编辑」。
//
// 目录由调用方注入（`挂目录()`），**不在这里算路径**：
// 「席位落在哪」在源码态与 portable exe 态是两个不同的答案，
// 而那正是今晚刚修过的那个坑（排除目录 在 exe 下整个失效）。
// lib 只管规则，路径集中在 server.js 一处解决。
const 内建 = 全部;
const 内建索引 = new Map(内建.map((x) => [x.名, x]));

let 席位目 = null;
let 缓 = { 时: 0, 表: [] };

function 挂目录(目录) { 席位目 = 目录 || null; 缓 = { 时: 0, 表: [] }; }

function 自建们() {
  if (!席位目) return [];
  const 现在 = Date.now();
  // 缓 3 秒：/api/seats 被在座栏 5 秒一拍地问，没必要每次都走盘；
  // 而 3 秒足够短，在文稿台改完协议切回来就能看见。
  if (缓.表.length && 现在 - 缓.时 < 3000) return 缓.表;
  let 表 = [];
  try { 表 = require('./席位档').全部(席位目); } catch (e) { 表 = []; }
  // 重名时**内建的赢**：一份放错名字的协议档不该悄悄顶掉总监。
  表 = 表.filter((x) => !内建索引.has(x.名));
  缓 = { 时: 现在, 表 };
  return 表;
}

/** 内建 + 自建。**这是名单的唯一出口**，别处不许再拼一份。 */
function 名单() { return 内建.concat(自建们()); }

const 按名 = (名) => {
  const k = String(名 || '');
  return 内建索引.get(k) || 自建们().find((x) => x.名 === k) || null;
};
const 已接模型 = () => 名单().filter((x) => x.接模型);
const 是已知 = (名) => !!按名(名);

module.exports = {
  // `全部` 保持是**内建那七席**（老调用方按数组用它，语义不变）；
  // 要含自定义的走 名单()。两个名字各有各的意思，不许混。
  全部, 内建, 名单, 按名, 已接模型, 是已知, 挂目录,
};
