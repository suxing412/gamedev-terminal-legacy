// 席位档.js — 一席＝一份协议文档（2026-09-02 批六，制作人拍板）。
//
// 制作人原话：「智能体协议就按照文档库里的，可以直接在自定义中跳转到文档库中开编辑器进行编辑」。
//
// 所以这里的设计只有一句话：**协议档是这一席的唯一事实源。**
// 席位页上没有表单——改名、改人设、改人格、改边界，一律去文稿台改那份 .md。
// 一个字段两个改法（页面上一个表单、文档里一份正文）就是两本账，
// 而两本账迟早会有一天只改了其中一本，且没有任何东西会报错。
//
// ── 落在哪 ────────────────────────────────────────────────────
// 落在 **terminal 文稿根**（源码仓）下的 `席位/`，不落 `<终端根>/席位`。
// 理由是今晚刚踩过的那个坑：终端根在源码态是仓根、在 portable exe 态是部署区，
// 两处各写各的，于是「源码态建的席位，换装之后不见了」——
// 与 排除目录 那条同型（2026-09-02 修）。
// 文稿根表里的 terminal 路在两种形态下是同一个，所以席位在两边也是同一批。
//
// ── 共守 ──────────────────────────────────────────────────────
// `席位/_共守.md` 是九席同一份的底线（同事不是助手、会说「这条我判错了」…），
// 取自 PRODUCT.md 的 Brand Personality。改它等于改全屋，所以它单独一份，
// 而不是抄进每一席的协议里——抄九份就一定有一天只改了其中三份。
'use strict';
const fs = require('fs');
const path = require('path');
const { 拆头 } = require('../render/md');

const 共守档名 = '_共守.md';

/** 席名 → 文件名。**洗一道**：席名会进路径，"现在不是用户输入"从来不是路径安全的理由。 */
function 档名(名) {
  const s = String(名 == null ? '' : 名)
    .replace(/[\\/:*?"<>|]/g, '')       // Windows 非法字符
    .replace(/\.\./g, '')               // 上跳段
    .replace(/^\.+/, '')                // 前导点（隐藏文件 / 当前目录）
    .trim();
  return s ? s + '.md' : null;
}

/** 目录不在就当没有席位，**不抛**——一个还没建过自定义席位的机器是正常状态。 */
function 列(目录) {
  let 项;
  try { 项 = fs.readdirSync(目录, { withFileTypes: true }); } catch (e) { return []; }
  return 项
    .filter((x) => x.isFile() && /\.md$/i.test(x.name) && x.name !== 共守档名)
    .map((x) => x.name)
    .sort();
}

/**
 * 读一份协议档 → 席位对象。
 *
 * frontmatter 用文稿台那把尺（render/md 的 拆头），**不另写一个解析器**：
 * 两个解析器对同一份文件给出不同结果，是这个项目已经反复付过学费的形状。
 *
 * 认得的头字段：名 / 接模型 / 模型 / 一句话。正文整段就是协议。
 */
function 读(目录, 档) {
  const 全 = path.join(目录, 档);
  let 文;
  try { 文 = fs.readFileSync(全, 'utf8'); } catch (e) { return null; }
  const { 头, 正文 } = 拆头(文);
  const h = 头 || {};
  const 名 = String(h.名 || path.basename(档, path.extname(档))).trim();
  if (!名) return null;
  // 接模型：显式写了才算接。**默认不接**——一个说不了话的席位登记在册是常态，
  // 而一个自称接了却答不出的席位会让屏上出现"正在思考"然后永远不结束。
  const 接 = /^(是|真|true|yes|1|接)$/i.test(String(h.接模型 || '').trim());
  return {
    名,
    接模型: 接,
    模型: String(h.模型 || '').trim() || null,
    // 一句话＝在座栏第二行显示的那句。没写就取正文第一句，仍然是文档里的原话。
    人设: String(h.一句话 || '').trim() || 首句(正文),
    自建: true,
    档,
    协议: 正文,
  };
}

/** 正文第一句。取不到就回空串——**不编一句**。 */
function 首句(正文) {
  const 行 = String(正文 || '').split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !/^[#>|\-*\s]/.test(l));
  if (!行.length) return '';
  return 行[0].slice(0, 60);
}

/** 全部自定义席位。读坏一份不影响其余——一份写坏的协议不该让整栏空掉。 */
function 全部(目录) {
  return 列(目录).map((f) => 读(目录, f)).filter(Boolean);
}

/** 共守段（九席同一份）。没有就回 null，界面照实说「还没立」。 */
function 共守(目录) {
  try {
    const { 正文 } = 拆头(fs.readFileSync(path.join(目录, 共守档名), 'utf8'));
    return 正文.trim() || null;
  } catch (e) { return null; }
}

/**
 * 新建一份协议档。**只建骨架，不替他写内容**——
 * 设计内容由制作人主导，这里给的是一张填空表，不是一份写好的人设。
 * 已存在就不覆盖（返回 已在）：覆盖一份协议＝无声地换掉一整席。
 */
function 建(目录, 名) {
  const f = 档名(名);
  if (!f) return { 行: false, 因: '席名洗完是空的' };
  const 全 = path.join(目录, f);
  if (fs.existsSync(全)) return { 行: false, 因: '已经有一席叫这个名字了', 已在: true, 档: f };
  const 模板 = [
    '---',
    '名: ' + 名,
    '接模型: 否',
    '模型: claude-opus-5',
    '一句话: ',
    '---',
    '',
    '## 本席',
    '',
    '共守那一段在 `_共守.md`，九席同一份，改它等于改全屋。这里只写这一席与别人不同的地方。',
    '',
    '- **职责** —— ',
    '- **人格特征** —— ',
    '- **语言风格** —— ',
    '- **招牌动作** —— ',
    '- **失手时** —— ',
    '- **边界（不做什么）** —— ',
    '',
    '## 试音',
    '',
    '同一件事，这一席会怎么说？写一句在这儿。',
    '**读着不像这一席，说明上面还没写准**，不是模型不听话。',
    '',
  ].join('\n');
  try {
    fs.mkdirSync(目录, { recursive: true });
    fs.writeFileSync(全, 模板, 'utf8');
  } catch (e) { return { 行: false, 因: String(e.message).slice(0, 120) }; }
  return { 行: true, 档: f, 路: 全 };
}

module.exports = { 全部, 读, 列, 建, 共守, 档名, 首句, 共守档名 };
