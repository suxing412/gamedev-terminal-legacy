// 席况.js — 每一席此刻在做什么。
//
// **这是「不许编」那条线的正面回答。**
//
// 2026-09-02 批五做在座栏时，设计稿上画的是「正在答话 / 起草 TK-234 / 回灌 4 源」。
// 那三句一句都没实现，理由写在提交信息里：按席的活动当时**没有任何数据源**，
// 照着画就是在屏上编一个状态（PRODUCT 原则五）。这个文件补的就是那个来源。
//
// 它只报终端**自己确知**的两件事：
//   ① 此刻有没有一条 /api/say 正在为这一席跑、跑了多久、它最近一次动手在做什么
//      —— 那句「在做什么」来自 SDK 的 tool_use 事件，也就是屏上转圈处显示的同一句话。
//      不是我们猜的，是坐席自己报的。
//   ② 上一次说话是什么时候 —— 会话档 `.session-<席>.json` 的 mtime（每答一句写一次）。
//
// **别的一律不报。**「在起草 TK-234」这种话，除非坐席自己说了它在读 TK-234，
// 否则不许出现在这一栏里。一栏会编状态的名单，比没有那一栏坏得多。
//
// 时钟一律从外面传进来（现在 / 起时），**不在这里调 Date.now()**——
// 那样判据就钉不住，而这个文件报的每一个数都要能被钉住。
'use strict';
const fs = require('fs');
const path = require('path');

/** 群聊那条线（没点名某一席）在表里的名字。用一个不可能与席名重名的键。 */
const 群键 = '·群';

function 开台() {
  const 在飞 = new Map();          // 席名 | 群键 → { 起时, 做, 来路 }

  const 键 = (席) => (席 ? String(席) : 群键);

  return {
    群键,

    /** 一条 /api/say 开跑。同一席重复开跑时后来者覆盖——那本来就是同一条线在续。 */
    开始(席, 现在, 来路) {
      在飞.set(键(席), { 起时: Number(现在) || 0, 做: null, 来路: 来路 || null });
    },

    /**
     * 坐席报了一次「我在动手做什么」。文本原样收下，**不加工**——
     * 它是坐席自己说的那句话，我们改写它就等于替它编。
     */
    在做(席, 做) {
      const v = 在飞.get(键(席));
      if (!v) return false;
      const s = String(做 == null ? '' : 做).trim();
      v.做 = s ? s.slice(0, 60) : null;
      return true;
    },

    /** 跑完了 / 断线了 / 崩了，都走这一条。**漏调就会留下一个永远在答话的幽灵。** */
    结束(席) { return 在飞.delete(键(席)); },

    /** 此刻这一席的状况。不在飞就回 null，不回一个「空的在飞」。 */
    况(席, 现在) {
      const v = 在飞.get(键(席));
      if (!v) return null;
      const 秒 = Math.max(0, Math.floor(((Number(现在) || 0) - v.起时) / 1000));
      return { 在答: true, 秒, 做: v.做 || null, 来路: v.来路 || null };
    },

    /** 调试与判据用：现在都有谁在飞。 */
    全况(现在) {
      const 出 = {};
      for (const k of 在飞.keys()) 出[k] = this.况(k === 群键 ? null : k, 现在);
      return 出;
    },

    /** 判据用：清干净。 */
    清() { 在飞.clear(); },
  };
}

/**
 * 上一次说话是什么时候。取会话档的 mtime——每答一句 写会话() 就写一次。
 *
 * **读不到就回 null，不回 0 也不回「很久以前」。** 会话档不存在有两种含义：
 * 这一席从来没说过话、或者档被清过；两种都不是「刚说完」，也都不是一个可以拿来
 * 算时长的数。PRODUCT 原则五。
 */
function 末话(终端根, 席) {
  const 档 = 席 ? path.join(终端根, `.session-${席}.json`) : path.join(终端根, '.session.json');
  try { return fs.statSync(档).mtimeMs; } catch (e) { return null; }
}

module.exports = { 开台, 末话, 群键 };
