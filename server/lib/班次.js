// 班次.js — 无人值守班次的额度闸与产出落点。
//
// 制作人 2026-08-29 拍板「都落地」，含额度上界。这里把上界做成**可执行的闸**，
// 不是文档里的一个数字——写在文档里的上限没有人执行，等于没有。
//
// 为什么额度闸是这套东西里最要紧的一道：
//   claude 订阅是 5h/周 窗口制。夜里烧掉的额度，白天补不回来。
//   一个无人值守的班次把窗口烧穿，代价不是「多花了钱」，是**制作人早上打开终端没得用**——
//   它偷的是人的工作时间，不是余额。所以闸的失效方向必须是「不开班」，不是「先开了再说」。
//
// 三条纪律：
//   一 · 闸开在**开班之前**，不在开班之后。事后统计拦不住已经烧掉的。
//   二 · 读不到用量记录时**拒绝开班**，不是放行。读不到 ≠ 没烧过。
//   三 · 拒绝要留痕并说得出还差多少，否则第二天没人知道昨晚为什么没干活。
'use strict';

const fs = require('fs');
const path = require('path');

// 一班的 output token 上限。保守取值——首班没有实测基线，
// 08-29 那次手工唤醒（跑了 9 个判据 + 读了一堆日志，约五分钟）的真实消耗当时没记，
// 因为 用量.jsonl 是同一天才加的。所以这个数是拍的，但它会随 用量.jsonl 攒出数据而可被修正。
// **拍一个数并执行它，好过不拍数而不设闸。**
// 一天的 output token 上限。
//
// 08-29 首版拍 60000，那时只有一个班。08-30 加到四类班次后**这个数与排期是打架的**：
// 工作日三班（夜间巡检 02:00 / 晨报 09:00 / 夜报 23:26）× 实测 19.4–22.9k ≈ 60k，正好顶死；
// 周末四班就是 80k+，后面的班必被闸挡，而且挡得毫无道理——是我排期时没算这笔账。
// 按实测最坏值重定：23k × 4 班 = 92k，取 120k 留余量。
//
// **提高它不等于放松保护。**真正防「烧掉制作人早上要用的额度」的是窗口水位闸（5小时窗 < 70%）；
// 这个日上限是第二道，抓的是「某一班失控地跑」这种异常，不是日常排期。
const 缺省上限 = 120000;

/** 当天日期串（本地时区，与流水口径一致） */
function 日串(现在) {
  const d = new Date(现在);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/**
 * 今日班次已耗（只算班次，不算人在输入框的交互）。
 * 回 { 读到, 出, 条数, 坏行, 因? }
 * **读不到与读到零是两回事**，必须分得开——见纪律二。
 */
function 今日已耗(用量文件, 现在 = Date.now()) {
  let 行;
  try { 行 = fs.readFileSync(用量文件, 'utf8').trim().split(/\r?\n/).filter(Boolean); }
  catch (e) {
    if (e && e.code === 'ENOENT') return { 读到: true, 出: 0, 条数: 0, 坏行: 0, 说: '还没有用量记录（文件不存在＝一次都没跑过）' };
    return { 读到: false, 因: '用量文件读不动：' + (e.code || e.message) };
  }
  const 今 = 日串(现在);
  let 出 = 0; let 条数 = 0; let 坏行 = 0;
  for (const l of 行) {
    let o; try { o = JSON.parse(l); } catch { 坏行 += 1; continue; }
    if (!o || !o.t) { 坏行 += 1; continue; }
    if (日串(new Date(o.t).getTime()) !== 今) continue;
    if (!String(o.来路 || '').startsWith('班次')) continue;   // 人在场的交互不占班次预算
    出 += Number(o.出) || 0;
    条数 += 1;
  }
  return { 读到: true, 出, 条数, 坏行 };
}

/**
 * 能不能开班。回 { 行, 因, 已耗, 上限, 余 }
 * 闸的失效方向：任何拿不准的情形一律**不开班**。
 */
function 可否开班(用量文件, 上限 = 缺省上限, 现在 = Date.now()) {
  const 上 = Number(上限) > 0 ? Number(上限) : 缺省上限;
  const 耗 = 今日已耗(用量文件, 现在);
  if (!耗.读到) {
    // 纪律二：读不到不等于没烧过。放行的话，一个坏掉的用量文件就能让闸失效。
    return { 行: false, 因: '拒绝开班：' + 耗.因 + '——读不到用量记录时一律不开班（读不到 ≠ 没烧过）', 上限: 上 };
  }
  if (耗.出 >= 上) {
    return { 行: false, 因: `拒绝开班：今日班次已耗 ${耗.出} output token，达到上限 ${上}`, 已耗: 耗.出, 上限: 上, 余: 0 };
  }
  return { 行: true, 因: `可开班：今日已耗 ${耗.出} / ${上}`, 已耗: 耗.出, 上限: 上, 余: 上 - 耗.出 };
}

/** 班次报告的落点。<终端根>/班次/<日>-<班次名>-<时分秒>.md */
function 报告路径(终端根, 班次名, 现在 = Date.now()) {
  const d = new Date(现在);
  const 时 = `${String(d.getHours()).padStart(2, '0')}${String(d.getMinutes()).padStart(2, '0')}${String(d.getSeconds()).padStart(2, '0')}`;
  const 净 = String(班次名 || '班次').replace(/[\\/:*?"<>|]/g, '_').slice(0, 40);
  return path.join(终端根, '班次', `${日串(现在)}-${净}-${时}.md`);
}

/**
 * 窗口水位闸：真实的订阅窗口烧到哪了。
 *
 * **这是 2026-08-29 首班坐席自己找出来的洞**，原话：
 *   「无人值守的额度闸是空转的……闸门把『文件不存在』判为『今日已耗 0』并放行——
 *     今天账户 5 小时窗口实际已烧到 33%，闸对此一无所知。钱在烧，闸看到的是 0。」
 *
 * 它是对的。`可否开班` 只数自己那本 用量.jsonl，而真正的约束是**共用的订阅窗口**——
 * 制作人白天的交互也在烧同一个窗口。一班烧得不多，不等于烧得起。
 *
 * 数据源是瞭望塔写的 额度读数.jsonl（本机 6292 条），每条形如
 *   {"t":…,"池":"claude","窗":"5小时","utilization":34,"resets_at":…}
 *
 * **失效方向：读不到就不开班。** 两种错的代价不对称——
 * 误拒的代价是今晚没干活（有 未开班 报告说明白，可恢复）；
 * 误放的代价是烧掉制作人早上要用的额度（不可恢复）。所以宁可误拒。
 */
function 窗口水位(额度文件, 窗名 = '5小时') {
  let 行;
  try { 行 = fs.readFileSync(额度文件, 'utf8').trim().split(/\r?\n/).filter(Boolean); }
  catch (e) { return { 读到: false, 因: '额度读数读不动：' + (e.code || e.message) }; }
  // 从尾往前找最近一条该窗的读数
  for (let i = 行.length - 1; i >= 0; i -= 1) {
    let o; try { o = JSON.parse(行[i]); } catch { continue; }
    if (!o || o['窗'] !== 窗名) continue;
    const u = Number(o.utilization);
    if (!Number.isFinite(u)) continue;
    return { 读到: true, 水位: u, 时刻: o.t, 复位于: o.resets_at || null };
  }
  return { 读到: false, 因: `额度读数里没有「${窗名}」窗的任何一条读数` };
}

// 读数最多允许多旧。实测瞭望塔每 2 分钟写一条 5 小时窗读数
// （3485 条 / 141 小时，间隔中位 120s、p99 132s），取 15 分钟＝中位数的 7 倍，
// 宽松到不会误伤正常抖动，又能立刻抓住塔阵亡——**同一份数据里最大间隔是 48740 秒（13.5 小时）**，
// 那正是塔死掉的那一段。
const 陈旧秒 = 900;

/** 窗口闸。回 { 行, 因, 水位?, 龄秒? } */
function 窗口可否(额度文件, 水位上限 = 70, 窗名 = '5小时', 现在 = Date.now(), 陈旧 = 陈旧秒) {
  const w = 窗口水位(额度文件, 窗名);
  if (!w.读到) return { 行: false, 因: '拒绝开班：' + w.因 + '——读不到真实水位时一律不开班（误拒可恢复，误放烧掉的是制作人早上要用的额度）' };

  // **读到的可能是死人的旧值。**
  // 窗口水位 从尾部倒扫取最近一条，但从不看它多旧。瞭望塔阵亡后最后一条读数会一直躺在那儿，
  // 09:00 的晨报拿它过闸，屏上画出来的「2% / 70%」跟新鲜读数长得一模一样——
  // 而真实水位可能已经 85%。**这比空白更坏：它取消了人的怀疑，并且照样把额度烧掉。**
  // 「读不到」有判据堵着，「读到的是陈的」原先一条都没有。08-30 红队第二条重级击杀。
  const 龄秒 = Math.round((现在 - new Date(w.时刻).getTime()) / 1000);
  if (!Number.isFinite(龄秒) || 龄秒 > 陈旧) {
    return {
      行: false,
      因: `拒绝开班：水位读数已经 ${Number.isFinite(龄秒) ? Math.round(龄秒 / 60) + ' 分钟' : '不知道多久'}没更新了`
        + `（正常 2 分钟一条，超 ${Math.round(陈旧 / 60)} 分钟即视为陈旧）——多半是瞭望塔不在写了，`
        + '此刻这个数不代表现状',
      水位: w.水位, 龄秒: Number.isFinite(龄秒) ? 龄秒 : null, 陈旧: true,
    };
  }
  if (w.水位 >= 水位上限) {
    return { 行: false, 因: `拒绝开班：${窗名}窗已烧到 ${w.水位}%，超过开班水位线 ${水位上限}%`, 水位: w.水位, 龄秒 };
  }
  return { 行: true, 因: `${窗名}窗水位 ${w.水位}% < ${水位上限}%（读数 ${龄秒} 秒前）`, 水位: w.水位, 龄秒 };
}

/**
 * 到点了吗（纯函数，可单测）。回 { 到, 因 }
 *
 * 抽成纯函数与塔的 守护判定 同一个理由：判断与副作用分开，判断才测得动。
 * 定点这件事一年只在特定时刻发生几次，靠等是等不出判据的。
 *
 * 窗口语义：只在 [到点, 到点+补跑窗口] 之间开班。
 *   · 有窗口，是为了兜「到点那一刻机器刚好没在」——早上开机还能补上。
 *   · 窗口有上界，是因为无限补跑意味着下午开机会莫名其妙跑一班夜班——**那是惊吓不是服务**。
 */
function 到点了吗(配, 现在 = Date.now()) {
  if (!配) return { 到: false, 因: '没有班次配置（缺省关，不缺省开）' };
  if (配.启用 === false) return { 到: false, 因: '配置里停用了' };
  if (!String(配.话 || '').trim()) return { 到: false, 因: '没写活干什么（话为空）' };

  // 仅星期：周末巡检只在周六周日跑。不补这一条，周末巡检会天天跑——
  // **而天天跑的周末巡检就不是周末巡检了。**
  // 因由必须与「还没到点」**用词不同**：屏上要把「今天不该跑」和「今天该跑但还没到」
  // 画成两样东西（周末巡检在周三没跑是正常，在周日没跑是故障）。
  // 两者共用一句「不到」的话，这一格就是假的。
  if (Array.isArray(配.仅星期) && 配.仅星期.length) {
    const 今星期 = new Date(现在).getDay();          // 0=周日 … 6=周六
    if (!配.仅星期.map(Number).includes(今星期)) {
      return { 到: false, 因: '今天不是它该跑的日子', 不该跑: true };
    }
  }

  const 片 = String(配.到点 || '').split(':');
  const h = Number(片[0]); const m = Number(片[1]);
  if (!Number.isFinite(h) || !Number.isFinite(m) || h < 0 || h > 23 || m < 0 || m > 59) {
    return { 到: false, 因: `到点写坏了：${配.到点}` };
  }
  const 窗 = Number(配.补跑窗口分) > 0 ? Number(配.补跑窗口分) : 120;
  const d = new Date(现在);
  const 过分 = (d.getHours() * 60 + d.getMinutes()) - (h * 60 + m);
  // 三种「不到」各带自己的标记。**不让调用方去正则匹配中文因由**——
  // 那等于把状态判断写进了文案里，改一个字就坏，而且前后端各匹配一次就是两把尺。
  if (过分 < 0) return { 到: false, 未到: true, 因: `还没到点（差 ${-过分} 分钟）` };
  if (过分 > 窗) return { 到: false, 过窗: true, 因: `过点太久（已过 ${过分} 分钟，补跑窗口 ${窗} 分钟）——补跑无上界的话，下午开机会莫名跑一班夜班` };
  return { 到: true, 因: `到点（已过 ${过分} 分钟，在 ${窗} 分钟补跑窗口内）` };
}

/**
 * 从班次表里挑出此刻该跑的那一个（纯函数，可单测）。回 班次对象 或 null。
 *
 * 三条：
 *   ① 停用的、没写活的，一概不看
 *   ② **今天已经跑过的先剔掉**——否则一个班的补跑窗口（默认 120 分钟）会把后面那个班
 *      一直挡在后面：09:00 的晨报要是排在 02:00 夜班后面，而夜班的窗口还没过，
 *      find 会一直选中夜班（它已跑过、什么也不做），晨报永远轮不上。
 *   ③ 先到先得：同时到点的取表里靠前那个（单飞，一次只跑一个）
 */
function 挑班次(表, 现在 = Date.now(), 跑过 = () => false) {
  return (Array.isArray(表) ? 表 : [])
    .filter((c) => c && c.启用 !== false && String(c.话 || '').trim() && !跑过(c.班次))
    .find((c) => 到点了吗(c, 现在).到) || null;
}

/**
 * 一个班次此刻的状况（纯函数，可单测）。回 { 态, 说, 档名? }
 *
 * **八种态，两两必须不同。**这是不变量二的落点：
 * 「没跑」「今天不该跑」「跑崩了」「被闸挡了」「终端整夜没起来」在屏上长得一样的话，
 * 早上看见一个灰点，你不知道该去查什么。
 *
 *   停用    配置里关了
 *   已跑    有今日报告，正常收尾
 *   未收尾  有今日报告，但跑崩了 / 被墙钟掐了
 *   被闸挡  额度闸或窗口闸拒绝开班，落了一份 未开班 报告
 *   今天不跑 仅星期 不含今天（周末巡检在周三）
 *   待跑    还没到点
 *   补跑中  过了点、在补跑窗口内、还没跑（瞬态）
 *   错过    **过了补跑窗口，什么都没有**——终端整夜没起来长这样，
 *           它跟「待跑」绝不能混：一个是还没轮到，一个是这一班这辈子没了
 *   运行中  开了班还没收（且进程知道它在跑）。一班要 5–7 分钟，这段时间里
 *           不给它一个自己的态，就只能假标成「补跑中」或「未收尾」
 *   断了    **开了班但没收，而进程也不认为它在跑**——跑到一半被杀 / 断电长这样。
 *           异厂评审的击杀原话：「进程在写出报告前被杀死，与调度器根本未启动时
 *           同样是『无报告、当前闸正常』，二者必然同态」。所以开班也要落盘，
 *           这一态才立得住——它跟「错过」要查的东西完全不同。
 *
 * 今日 = { 收班条, 开班条, 未开班, 未开班因, 在跑 }
 */
function 班况(配, 现在 = Date.now(), 今日 = {}) {
  if (!配) return { 态: '读不到', 说: '没有这个班次的配置' };
  if (配.启用 === false) return { 态: '停用', 说: '配置里停用了' };

  if (今日.收班条) {
    const c = 今日.收班条;
    return c.结果 === '正常收尾'
      ? { 态: '已跑', 说: `${c.用时秒} 秒 · ${c.出 != null ? c.出 + ' token' : '用量读不到'}`, 档名: c.档名 }
      : { 态: '未收尾', 说: c.因 || '未正常收尾', 档名: c.档名 };
  }
  // 开了班没收班：进程认它在跑＝运行中；不认＝跑到一半断了
  if (今日.开班条) {
    return 今日.在跑
      ? { 态: '运行中', 说: `${Math.round((现在 - new Date(今日.开班条.起于).getTime()) / 1000)} 秒前开的班，还在跑`, 档名: 今日.开班条.档名 }
      : { 态: '断了', 说: '开了班但没收尾，进程也不认为它在跑——多半是跑到一半被杀或断电', 档名: 今日.开班条.档名 };
  }
  if (今日.未开班) return { 态: '被闸挡', 说: 今日.未开班因 || '闸拒绝了开班' };

  const d = 到点了吗(配, 现在);
  if (d.不该跑) return { 态: '今天不跑', 说: d.因 };
  if (d.到) return { 态: '补跑中', 说: d.因 };
  if (d.未到) return { 态: '待跑', 说: d.因 };
  if (d.过窗) return { 态: '错过', 说: d.因 + '——这一班今天不会再跑了' };
  return { 态: '读不到', 说: d.因 };          // 到点写坏了之类
}

/**
 * 今天这个班跑过没有（纯函数，可单测）。
 *
 * **看索引，不看报告文件名。** 首版按文件名前缀判，结果是给班次改个名字
 * （夜间自检 → 夜间巡检）旧报告就匹配不上，同一天会再跑一班——20k token 白烧，
 * 而且没人会发现，因为两份报告看起来都很正常。08-30 02:32 换四班配置时当场撞到。
 *
 * **开班也算跑过。** 一班跑到一半崩了不该被自动重跑：崩了要人去看
 * （页面上是「断了」那一态），不是让它自己再撞一次。
 */
function 今日跑过(条们, 班次名, 现在 = Date.now()) {
  const 今 = 日串(现在);
  return (Array.isArray(条们) ? 条们 : []).some((o) => o
    && o.班次 === 班次名
    && 日串(new Date(o.t).getTime()) === 今);
}

