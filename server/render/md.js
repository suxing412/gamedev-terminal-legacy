// md.js — 受限 Markdown → HTML（M1c · A4；2026-08-31 扩写至文档语法面）
//
// **为什么自写而不是装 marked**：施工令 §4 把 `marked` 列为候选，但同一行写着
// 「依赖白名单**待拍板⑤**，不放行则自写受限子集」。拍板⑤ 至今未裁，所以走的是它自己写好的退路。
//
// **2026-08-31 扩写的由来**：本渲染器原先只认 `#`/`##`/`###`、`>`、`-` 列表、空行分段。
// 实测拿它渲染 `设计文档.md`（547 行）：
//     <pre> 0 个   <table> 0 个   <hr> 0 个   <h4> 0 个   <ol> 0 个
//     残留 <p>|表格行 83   <p>#### 18   <p>``` 20   <p>--- 20   <p>1. 9
// **150/547 行渲染错，约 27%。**而且不只是难看——**代码围栏里的 `-` 和 `#` 会被当成列表和标题吃掉**，
// 结构被搅乱。班次报告与日报都走这个渲染器，所以这是今天就在坏的东西，不是为编辑器新加的需求。
//
// **安全是本文件的第一职责，不是附带**：条目标题与链接直接来自第三方 RSS，
// 精编正文来自模型——三样都是不可信输入。故顺序写死：**先转义，再上内联规则**。
// 反过来（先生成标签再转义）等于把自己刚插的标签也转义掉，或者更糟：把别人插的标签放过去。
// 链接协议只放 http/https：`javascript:` 与 `data:` 一律降级成纯文本，不是过滤掉字符了事——
// 「看起来像链接但点不动」比「悄悄变成一个能执行的链接」安全得多，也更容易在页面上被人发现。

const 转义表 = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const 转义 = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (c) => 转义表[c]);

// 链接协议闸。相对路径（/digest/… 这种本站内的）放行，其余一律要求 http/https。
function 安全链(u) {
  const s = String(u || '').trim();
  if (!s) return null;
  if (s.startsWith('/') && !s.startsWith('//')) return s;   // 站内相对路径
  return /^https?:\/\//i.test(s) ? s : null;                // 其余必须显式 http(s)
}

// 内联规则。**只在已转义的文本上跑**——所以这里的正则看到的 `&lt;` 已经是字面量，
// 不可能再被解释成标签。规则顺序有意义：代码段最先吃掉，免得它内部的下划线被当成斜体。
function 内联(已转义) {
  // 占位符用 NUL 包起来，不用 ` C0 ` 那种可打印形式。
  // 旧版是 ` C${i} `，于是正文里真出现「维生素 C3 含量」时，那个 ` C3 ` 会被当成占位符
  // 换成第 4 个代码段——**吃字，且不报错**。NUL 不可能来自转义输出，先剥干净再用。
  let s = String(已转义 == null ? '' : 已转义).replace(/\u0000/g, '');
  const 代码槽 = [];
  s = s.replace(/`([^`]+)`/g, (_, c) => `\u0000${代码槽.push(`<code>${c}</code>`) - 1}\u0000`);
  // 地址允许**成对括号**：`…/wiki/Foo_(bar)` 这类链接极常见，
  // 用 `[^)\s]+` 会截在第一个右括号上，剩一个孤零零的 `)` 漏进正文（首版实测如此）。
  s = s.replace(/\[([^\]]*)\]\(((?:[^()\s]|\([^()\s]*\))+)\)/g, (全, 文, 址) => {
    // 址在转义阶段被动过 &amp;（URL 里 & 很常见）——放回原样再判协议，判完输出时重新转义。
    const 原址 = String(址).replace(/&amp;/g, '&');
    const 安 = 安全链(原址);
    if (!安) return 文 || 转义(原址);   // 协议不合规：降级成纯文本，不留可点的口
    return `<a href="${转义(安)}" rel="noopener noreferrer" target="_blank">${文}</a>`;
  });
  s = s.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  s = s.replace(/(^|[\s（(])_([^_]+)_(?=$|[\s，。）)])/g, '$1<em>$2</em>');
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => 代码槽[Number(i)]);
}

// ── 表格 ──────────────────────────────────────────────────────────────
// 拆单元格。`\|` 是转义竖线，不当分隔符——协议库里的表格有写 `a \| b` 的。
function 拆格(行) {
  let s = 行.trim();
  if (s.startsWith('|')) s = s.slice(1);
  if (/(?<!\\)\|$/.test(s)) s = s.replace(/\|$/, '');
  return s.split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, '|'));
}

// 分隔行：每格形如 ---、:---、---:、:---:
const 是分隔行 = (行) => {
  const s = 行.trim();
  if (!s.includes('|') && !/^:?-{3,}:?$/.test(s)) return false;
  const 格 = 拆格(s);
  return 格.length > 0 && 格.every((c) => /^:?-{2,}:?$/.test(c));
};

const 对齐 = (格) => {
  const 左 = 格.startsWith(':');
  const 右 = 格.endsWith(':');
  if (左 && 右) return 'center';
  if (右) return 'right';
  if (左) return 'left';
  return '';
};

/**
 * 拆头(md) → { 头, 正文, 头行数 }
 *
 * 剥掉文件开头那段 `---` 包着的 frontmatter。
 *
 * **这不是新需求，是既存的错。**实测：全库 959 份 md 里 **339 份以 `---` 开头**，
 * 而这个渲染器不认识 frontmatter——那 339 份在文稿台上，开头那几行 YAML 是被当**正文**画出来的：
 * 一条 `<hr>` + 若干 `<p>name: …</p>` + 又一条 `<hr>`。三分之一的文档顶着一坨元数据。
 *
 * 解析上只认最简的 `键: 值`（一层，不进嵌套）——**够用就停**：
 * 这里要的只是「用途」这一个键，为它请一个 YAML 解析器进来是杀鸡用牛刀，
 * 而且多一个依赖就多一个要跟着升级的东西。认不出的行原样收进 `头.其余`，不猜、不丢。
 *
 * **头行数 必须回给调用方。**行号锚点是文稿台记号栏跳转的依据；剥掉几行就要把后面的行号
 * 补回几行，否则「跳到第 12 行」会稳定地跳到第 8 行——**而它不报错，只是跳错地方**。
 */
function 拆头(md) {
  // **BOM 写成 \uFEFF 转义，不写真字符。**源码里一个裸的 U+FEFF 是看不见的，
  // 任何清理控制字符的工具、任何顺手 trim 一下的编辑器都会静默把它删掉——
  // 删掉之后这一行照样跑、照样不报错，只是不再剥 BOM 了。（这条我犯过两次。）
  const 全 = String(md == null ? '' : md).replace(/^\uFEFF/, '');
  // 必须是**第一行**就是 `---`。文中间的 `---` 是分隔线，不是头。
  const m = 全.match(/^---[ \t]*\r?\n([\s\S]*?)\r?\n---[ \t]*(\r?\n|$)/);
  if (!m) return { 头: null, 正文: 全, 头行数: 0 };
  const 头 = { 其余: [] };
  for (const l of m[1].split(/\r?\n/)) {
    // 缩进行属于上一个键的嵌套内容，本解析器不进去——原样收进 其余
    const kv = /^([A-Za-z_一-龥][\w一-龥-]*)\s*:\s*(.*)$/.exec(l);
    if (kv && !/^\s/.test(l)) 头[kv[1]] = kv[2].trim();
    else if (l.trim()) 头.其余.push(l);
  }
  return { 头, 正文: 全.slice(m[0].length), 头行数: m[0].replace(/\r?\n$/, '').split(/\r?\n/).length };
}

/**
 * 渲染。支持：
 *   · 标题 `#`–`######`
 *   · 代码围栏 ``` / ~~~（**围栏内一律不解析**，原样转义输出）
 *   · 表格（含 `:---:` 对齐）
 *   · 分隔线 `---` / `***` / `___`
 *   · 无序列表 `-`（两级）与有序列表 `1.`（两级）
 *   · 引用 `>`
 *   · 空行分段
 * 认不出的行按段落走——**不静默丢弃**：日报少一行，读的人不会知道自己少看了什么。
 */
function 渲染(md, 选项 = {}) {
  // BOM 与 frontmatter 都在 拆头 里剥掉，**只剥一处**。
  //
  // 这里原本自己也剥一次 BOM。加了 拆头 之后就成了两处剥同一样东西——
  // 而那使得「md 不剥 BOM」那条变异打在死代码上：拆掉这里的，拆头 照剥，判据不红。
  // **同一件事写两遍，第二遍会悄悄把第一遍的判据架空。**（自证能红台当场照出来的。）
  //
  // 行号要补回去：剥掉 N 行之后，正文第 1 行其实是文件第 N+1 行，
  // 而记号栏跳转与编辑态的段落按钮都按这个数走。不补的话跳转稳定偏 N 行，**且不报错**。
  const 拆 = 拆头(md);
  const 正 = 拆.正文;
  const 行偏 = 拆.头行数;
  const 行 = 正.split(/\r?\n/);
  const 出 = [];

  // 行号锚点。文稿台的记号栏靠它跳到对应段落；编辑态的段落级按钮也靠它，
  // 把「点了预览里这一段」翻译成「往源码第几行插记号」。
  // **默认不开**：日报与班次报告用不着，多一堆属性只是噪声。
  const 标行 = 选项.行号 === true;
  let 当行 = 0;                                   // 当前正在处理的源码行（0 基）
  const 属 = () => (标行 ? ` data-行="${当行 + 1 + 行偏}"` : '');

  // 列表状态。层 0=不在列表 / 1=一级 / 2=二级；层标记住每层是 ul 还是 ol。
  // 子列表必须**嵌在父 li 内部**——`<ul>` 直接套 `<ul>` 是非法结构
  // （浏览器能凑合渲染，但缩进语义与无障碍树都错）。
  // 所以一级的 li 先不闭合，等它确定没有子项、或子列表已收完，才补 `</li>`。
  let 层 = 0;
  const 层标 = [null, null, null];
  let 父未闭 = false;
  const 闭父 = () => { if (父未闭) { 出.push('</li>'); 父未闭 = false; } };
  const 收到 = (目标) => {
    if (层 === 2 && 目标 <= 1) { 出.push(`</${层标[2]}>`); 层标[2] = null; 层 = 1; 闭父(); }
    if (层 === 1 && 目标 === 0) { 闭父(); 出.push(`</${层标[1]}>`); 层标[1] = null; 层 = 0; }
  };

  for (let i = 0; i < 行.length; i++) {
    当行 = i;
    const 原行 = 行[i];
    const 行文 = 原行.replace(/\s+$/, '');

    // ① 代码围栏。**必须最先判**——围栏里的 `#`、`-`、`|` 都是内容，不是语法。
    //    这正是旧版最坏的那个 bug：围栏内的行被当成标题和列表吃掉，结构被搅乱。
    const 开围 = 行文.match(/^\s{0,3}(```+|~~~+)\s*([^\s`]*)\s*$/);
    if (开围) {
      收到(0);
      const 栅 = 开围[1][0];                     // ` 或 ~
      const 长 = 开围[1].length;
      const 语 = 开围[2] || '';
      const 码 = [];
      let j = i + 1;
      for (; j < 行.length; j++) {
        const 收 = 行[j].match(/^\s{0,3}([`~]+)\s*$/);
        // 收口栅栏必须同字符、且不短于开口（照 CommonMark）
        if (收 && 收[1][0] === 栅 && 收[1].length >= 长) break;
        码.push(行[j].replace(/\s+$/, ''));
      }
      const 类 = 语 ? ` class="lang-${转义(语)}"` : '';
      出.push(`<pre${属()}><code${类}>${转义(码.join('\n'))}</code></pre>`);
      // 围栏没收口就走到文末：也照样输出，不丢内容。i 停在 j（收口行或末尾）
      i = j;
      continue;
    }

    if (!行文.trim()) { 收到(0); continue; }

    // ② 表格。要前瞻一行——单独一行 `| a | b |` 不算表格，必须跟着分隔行。
    if (行文.includes('|') && i + 1 < 行.length && 是分隔行(行[i + 1])) {
      收到(0);
      const 头 = 拆格(行文);
      const 齐 = 拆格(行[i + 1]).map(对齐);
      const 体 = [];
      let j = i + 2;
      for (; j < 行.length; j++) {
        const t = 行[j].replace(/\s+$/, '');
        if (!t.trim() || !t.includes('|')) break;
        体.push(拆格(t));
      }
      const 格式 = (n) => (齐[n] ? ` style="text-align:${齐[n]}"` : '');
      const 头行 = 头.map((c, n) => `<th${格式(n)}>${内联(转义(c))}</th>`).join('');
      const 体行 = 体.map((r) => {
        // 少写的格补空、多写的格照收——**不丢内容**，宁可表格歪也不吞字
        const 格 = r.length >= 头.length ? r : r.concat(Array(头.length - r.length).fill(''));
        return `<tr>${格.map((c, n) => `<td${格式(n)}>${内联(转义(c))}</td>`).join('')}</tr>`;
      }).join('\n');
      出.push(`<table${属()}>\n<thead><tr>${头行}</tr></thead>` +
        (体行 ? `\n<tbody>\n${体行}\n</tbody>` : '') + '\n</table>');
      i = j - 1;
      continue;
    }

    // ③ 分隔线。放在列表之前判：`---` 不该被当成别的东西。
    if (/^\s{0,3}(-{3,}|\*{3,}|_{3,})\s*$/.test(行文)) { 收到(0); 出.push(`<hr${属()}>`); continue; }

    // ④ 列表（无序 `-` / 有序 `1.`）
    const 缩进 = (行文.match(/^ */) || [''])[0].length;
    const 无序 = 行文.trim().match(/^-\s+(.*)$/);
    const 有序 = 行文.trim().match(/^\d{1,9}[.)]\s+(.*)$/);
    if (无序 || 有序) {
      const 标 = 无序 ? 'ul' : 'ol';
      const 本层 = 缩进 >= 2 ? 2 : 1;
      const 文 = 内联(转义((无序 || 有序)[1]));
      if (本层 === 1) {
        收到(1);
        // 同一层换了列表类型（- 之后接 1.）：收掉再开，不硬塞进去
        if (层 === 1 && 层标[1] !== 标) 收到(0);
        if (层 === 0) { 出.push(`<${标}>`); 层标[1] = 标; 层 = 1; } else 闭父();
        出.push(`<li${属()}>${文}`); 父未闭 = true;
      } else {
        // 孤儿子项（没有一级父项就先来了缩进项）：补一个空父项兜住，不丢内容
        if (层 === 0) { 出.push(`<${标}>`); 层标[1] = 标; 层 = 1; 出.push('<li>'); 父未闭 = true; }
        if (层 === 2 && 层标[2] !== 标) { 出.push(`</${层标[2]}>`); 层 = 1; 层标[2] = null; }
        if (层 === 1) { 出.push(`<${标}>`); 层标[2] = 标; 层 = 2; }
        出.push(`<li${属()}>${文}</li>`);
      }
      continue;
    }
    收到(0);

    // ⑤ 标题。**h1–h6**（旧版只到 h3，于是 18 个 `####` 全掉进段落）
    const 题 = 行文.match(/^\s{0,3}(#{1,6})\s+(.*)$/);
    if (题) {
      const n = 题[1].length;
      // 结尾的 ` ###` 是闭合式写法，不是内容
      const 文 = 题[2].replace(/\s+#+\s*$/, '');
      出.push(`<h${n}${属()}>${内联(转义(文))}</h${n}>`);
      continue;
    }

    const 引 = 行文.match(/^\s{0,3}>\s?(.*)$/);
    if (引) { 出.push(`<blockquote${属()}>${内联(转义(引[1]))}</blockquote>`); continue; }

    出.push(`<p${属()}>${内联(转义(行文))}</p>`);
  }
  收到(0);
  return 出.join('\n');
}

module.exports = { 渲染, 拆头, 转义, 内联, 安全链, 拆格, 是分隔行 };
