// 顶况.test.js — 顶栏读数的写法。
//
// 顶栏是这块屏上唯一一处**一直在视野里**的地方。它写错一个字，
// 人就会照着错的那个字安排接下来一小时。2026-08-31 巡礼实测抓到两条：
//   ① 登录还剩 40 分钟，屏上写「登录 0h」——`Math.floor(40/60)`。
//      小于一小时的整个区间（也正是唯一要紧的那个区间）被压成一个读着像零的数。
//      而横幅的临期线是 30 分：30–59 分之间，顶栏喊 0、横幅说没事，同一份数据两种说法。
//   ② 额度只报周窗口，还把「（09-04 19:00 重置）」整串摆出来——实测 197px，
//      占整条顶况的 31%；而当下真正会把人拦住的 5 小时窗口一个字都没有。
'use strict';
const assert = require('node:assert');
const test = require('node:test');
const fs = require('node:fs');
const path = require('node:path');

const { 登录文, 额度文, 报重置线, 人闸文, 产线文, 龄文, 卡线分 } = require('../public/顶况.js');
const { 久档 } = require('../public/闸分组.js');

// ── 一、登录 ──────────────────────────────────────────────────

test('守① **40 分钟不许写成 0h**（案发现场原样：/api/cred 回 剩余分=40）', () => {
  const s = 登录文('有效', 40);
  assert.ok(!/\b0h/.test(s), `实得「${s}」—— 0h 读起来就是"已经没了"`);
  assert.match(s, /40/, '要把 40 这个数说出来');
  assert.match(s, /分/, '小于一小时就该用分钟这个刻度');
});

test('守①b 小于一小时的**整个区间**都要说得出话来', () => {
  for (const m of [1, 5, 29, 30, 31, 45, 59]) {
    const s = 登录文('有效', m);
    assert.ok(!/\b0h/.test(s), `${m} 分写成了「${s}」`);
    assert.ok(s.includes(String(m)), `${m} 分写成了「${s}」，看不出还剩多少`);
  }
});

test('守①c 与横幅的临期线不许各说各的（30 分是同一条线）', () => {
  // 横幅在 剩余分 < 30 时出现。顶栏在 30–59 分必须仍报得出真实分钟数，
  // 否则会出现「顶栏喊 0h、横幅说没事」这种同源两说。
  for (const m of [30, 40, 59]) {
    assert.match(登录文('有效', m), new RegExp(`${m} 分`), `${m} 分没如实报`);
  }
});

test('守①d 一个半小时以上才换成小时刻度，且不许丢精度到看不出差别', () => {
  assert.match(登录文('有效', 90), /1\.5h/);
  assert.match(登录文('有效', 200), /3\.3h/);
  assert.match(登录文('有效', 700), /12h/, '十小时以上就没必要报小数了');
  assert.notStrictEqual(登录文('有效', 90), 登录文('有效', 150), '1.5h 与 2.5h 不能写成同一串');
});

test('守①e 非有效态照实说，不拿分钟数糊弄', () => {
  assert.strictEqual(登录文('过期', -12), '登录过期');
  assert.strictEqual(登录文('临期', 12), '登录临期');
  assert.strictEqual(登录文('未登录', null), '登录未登录');
  assert.strictEqual(登录文('有效', null), '登录—', '态说有效但没有数字时，只能说不知道');
  assert.strictEqual(登录文('有效', 0), '登录已过期');
});

// ── 二、额度 ──────────────────────────────────────────────────

const 窗 = (l, p, r) => ({ label: l, pct: p, reset: r });
const 现场 = [窗('5小时', 15, '09-01 01:50'), 窗('周', 21, '09-04 19:00')];

test('守② **5 小时窗口必须出现**（它才是当下会把人拦住的那道）', () => {
  const r = 额度文(现场);
  assert.match(r.文, /5h 15%/, `实得「${r.文}」—— 只报周窗口等于把当下那道闸藏起来`);
  assert.match(r.文, /周 21%/);
});

test('守②b 低水位时不摆重置时刻（21% 的时候它是噪音，还占着顶栏三分之一）', () => {
  const r = 额度文(现场);
  assert.ok(!r.文.includes('重置'), `实得「${r.文}」`);
  assert.ok(!/09-04|01:50/.test(r.文), '重置时刻不该出现在正文里');
  assert.strictEqual(r.紧, null);
  // 但它不许消失——挪进 title，要的时候还够得着
  assert.match(r.详, /09-04 19:00/);
  assert.match(r.详, /01:50/);
});

test('守②c **快撞顶时重置时刻要摆出来**（这时"什么时候恢复"才是那个问题）', () => {
  const 高 = [窗('5小时', 92, '09-01 01:50'), 窗('周', 21, '09-04 19:00')];
  const r = 额度文(高);
  assert.match(r.文, /01:50 重置/, `实得「${r.文}」`);
  assert.strictEqual(r.紧, '5小时');
  assert.ok(!r.文.includes('09-04'), '只摆快撞顶那一个的重置时刻，两个都摆就回到原来的宽度问题上去了');
});

test('守②d 两个都过线时，摆水位最高那个的', () => {
  const r = 额度文([窗('5小时', 75, 'A'), 窗('周', 96, 'B')]);
  assert.strictEqual(r.紧, '周');
  assert.match(r.文, /B 重置/);
});

test('守②e 线就在 70 上（69 不摆、70 摆）', () => {
  assert.strictEqual(额度文([窗('周', 69, 'X')]).紧, null);
  assert.strictEqual(额度文([窗('周', 70, 'X')]).紧, '周');
  assert.strictEqual(报重置线, 70);
  // 线可传入覆盖
  assert.strictEqual(额度文([窗('周', 50, 'X')], 40).紧, '周');
});

test('守②f 没有窗口就说没有，不显示一个 0%', () => {
  assert.strictEqual(额度文([]).文, '额度—');
  assert.strictEqual(额度文(null).文, '额度—');
  assert.ok(!/0%/.test(额度文([]).文), 'PRODUCT 原则五：读不到就说读不到，绝不拿 0 冒充');
});

// ── 三、接线 ──────────────────────────────────────────────────

test('守③ app.js 用的是这一份，没有自己再写一份', () => {
  const s = fs.readFileSync(path.join(__dirname, '..', 'public', 'app.js'), 'utf8');
  assert.match(s, /self\.顶况/, 'app.js 没有引用 public/顶况.js');
  assert.ok(!/Math\.floor\(c\.剩余分 \/ 60\)/.test(s), '那行把 40 分钟写成 0h 的代码还在');
  assert.ok(!/周额度 \$\{周\.pct\}%/.test(s), '只报周窗口的旧写法还在');
});

test('守③c **整份窗口原样交出去**，调用处不许先挑一道', () => {
  // 挑哪个窗口、怎么写，是 顶况.js 一处的决定（守②系列在盯着它）。
  // 调用处再滤一次，等于把同一个决定放在两个地方，而其中一处没有任何判据看着——
  // 「只报周窗口」这个毛病就能原封不动地从这里回来。
  const s = fs.readFileSync(path.join(__dirname, '..', 'public', 'app.js'), 'utf8');
  const i = s.indexOf('顶况文.额度文(');
  assert.ok(i > 0, '找不到 额度文 的调用');
  const 实参 = s.slice(i + '顶况文.额度文('.length, s.indexOf(');', i));
  assert.ok(!/\.filter\(|\.find\(|label\s*===/.test(实参),
    `调用处挑了窗口：额度文(${实参}) —— 挑选只能发生在 顶况.js 里`);
});

test('守③b 顶况.js 在 index.html 里排在 app.js 之前', () => {
  const h = fs.readFileSync(path.join(__dirname, '..', 'public', 'index.html'), 'utf8');
  const a = h.indexOf('顶况.js'); const b = h.indexOf('src="app.js"');
  assert.ok(a >= 0, 'index.html 没引 顶况.js —— app.js 顶层解构会炸，整个前端不跑');
  assert.ok(a < b, '顶况.js 必须排在 app.js 之前');
});

// ── 四、拆栏之后的三格（2026-09-02 顶条评审）────────────────────
//
// 这一组盯的是「顶条成了唯一一直在视野里的东西」之后的两格措辞。
// 每一条都对着评审里一条**有出处的**故障，不是凭空想的边角。

test('守④ 人闸格不许渲染出 `1null`（/api/attn 实测 G13/G14/G25/G24 动作键是 null）', () => {
  const r = 人闸文([{ 动作键: null, 闸名: null, n: 1, 最久小时: 30 }], 24, 久档);
  assert.ok(!/null/.test(r.文), `实得「${r.文}」—— 屏上出现 null 就是把 bug 印给人看`);
  assert.match(r.文, /1待裁/, '认不出动作键要有个说得过去的回落词');
});

test('守④b 闸名能顶上：动作键没有但闸名有，就用闸名', () => {
  const r = 人闸文([{ 动作键: '', 闸名: '方向裁决', n: 3, 最久小时: 10 }], 24, 久档);
  assert.match(r.文, /3方向裁决/, `实得「${r.文}」`);
});

test('守⑤ 按最久停摆排序、最多三批、余下并成 +N（不许悄悄丢）', () => {
  const r = 人闸文([
    { 动作键: '验收', n: 24, 最久小时: 337 },
    { 动作键: '定夺', n: 1, 最久小时: 155 },
    { 动作键: '解除停靠', n: 11, 最久小时: 135 },
    { 动作键: '复核', n: 4, 最久小时: 40 },
    { 动作键: '答话', n: 2, 最久小时: 9 },
  ], 24, 久档);
  assert.strictEqual(r.文, '24验收 · 1定夺 · 11解除停靠 +6',
    '排序或并批不对：' + r.文);
  // **+6 不能少**：少了它，屏上说的总数就比真实的小，而这块屏最不能干的就是报小
  assert.match(r.文, /\+6/, '第四批往后的 6 件被吞了');
});

test('守⑤b 只有三批时不许拖一条空的 +0 尾巴', () => {
  const r = 人闸文([{ 动作键: '验收', n: 2, 最久小时: 30 }], 24, 久档);
  assert.ok(!/\+/.test(r.文), `实得「${r.文}」`);
});

test('守⑥ 年龄章用传进来的 久档，顶条不许自己写阈值', () => {
  // 同一份数据，换一把尺就该换一个档——证明它真的在用外面那把尺
  const 数 = [{ 动作键: '验收', n: 1, 最久小时: 100 }];
  const 甲 = 人闸文(数, 24, 久档);        // 100/24 = 4.2 倍 → 久档2
  const 乙 = 人闸文(数, 200, 久档);       // 100/200 = 0.5 倍 → 久档0
  assert.notStrictEqual(甲.档, 乙.档, '换了阈值档位没变 —— 说明阈值写死在顶条里了');
  assert.strictEqual(甲.档, 久档(100, 24));
  assert.strictEqual(乙.档, 久档(100, 200));
  assert.strictEqual(甲.章, '4天', '年龄章要按整天报：实得 ' + 甲.章);
});

test('守⑥b 不满一天不出年龄章（半天挂个「0天」比不挂更坏）', () => {
  assert.strictEqual(人闸文([{ 动作键: '验收', n: 1, 最久小时: 5 }], 24, 久档).章, null);
});

test('守⑦ 读不到要说读不到，**不许说 0**（PRODUCT 原则五）', () => {
  const r = 人闸文(null, 24, 久档);
  assert.match(r.文, /读不到/, `实得「${r.文}」`);
  assert.ok(!/^人闸 0$|\b0\b/.test(r.文), '把"不知道"写成了一个确定的好消息');
  // 真的一件都没有，是另一回事，要说得出来
  assert.match(人闸文([], 24, 久档).文, /没有等你的/);
});

// ── 产线格：六态 ──────────────────────────────────────────────
//
// **判据必须给定时钟。**产线文 拿 现在 作参数而不是自己 Date.now()，
// 就是为了这一组能钉死；顺带也让「跑龄」这个量在判据里是可复现的。

const 现在 = Date.parse('2026-09-02T01:00:00Z');
const 跑 = (号, 分) => ({ 单号: 号, 起时: new Date(现在 - 分 * 60000).toISOString() });

test('守⑧① 读不到就说读不到（不是「产线空闲」——那是个确定的好消息）', () => {
  assert.strictEqual(产线文({ 读不到: true }, 现在).文, '产线 读不到');
  assert.strictEqual(产线文({}, 现在).文, '产线 读不到', '在跑 不是数组＝没读着，不许当成零');
  assert.strictEqual(产线文({ 读不到: true }, 现在).级, '警');
});

test('守⑧② 有单在跑且最久超 180 分 → 点名那一单说「卡」', () => {
  const r = 产线文({ 在跑: [跑('TK-201', 252), 跑('TK-233', 4)], 待派: 0, 在途: 0, 闸数: 0 }, 现在);
  assert.match(r.文, /在跑 2/);
  assert.match(r.文, /TK-201 卡 4° 12′/, `实得「${r.文}」`);
  assert.strictEqual(r.级, '警');
});

test('守⑧②b 卡线就在 180 分（179 不卡、180 卡）—— 来自 journal 自己写的超时闸', () => {
  assert.strictEqual(卡线分, 180);
  assert.ok(!/卡/.test(产线文({ 在跑: [跑('A', 179)] }, 现在).文));
  assert.match(产线文({ 在跑: [跑('A', 180)] }, 现在).文, /卡/);
});

test('守⑧③ 正常在跑报最久跑龄（**不是只报个数**）', () => {
  const r = 产线文({ 在跑: [跑('A', 42), 跑('B', 4)], 待派: 0, 在途: 0, 闸数: 0 }, 现在);
  assert.strictEqual(r.文, '在跑 2 · 最久 42′', `实得「${r.文}」`);
  assert.strictEqual(r.级, '常');
});

test('守⑧③b 有单但起时读不出来时，不编一个龄出来', () => {
  const r = 产线文({ 在跑: [{ 单号: 'A' }, { 单号: 'B', 起时: '不是时间' }] }, 现在);
  assert.strictEqual(r.文, '在跑 2', `实得「${r.文}」—— 编出来的龄比没有龄坏`);
});

test('守⑧④ 零在跑但管线里有活 → 说待跑（这是派单器可能死了，不是闲）', () => {
  assert.strictEqual(产线文({ 在跑: [], 待派: 11, 在途: 0, 闸数: 61 }, 现在).文, '零在跑 · 待跑 11');
  assert.strictEqual(产线文({ 在跑: [], 待派: 0, 在途: 2, 闸数: 0 }, 现在).文, '零在跑 · 待跑 2',
    '在途也算进去——它同样意味着"有活但没跑起来"');
});

test('守⑧④b **不许叫「待派」**——那个词在台账里是一个具体状态，这里是好几个的和', () => {
  // 案发 2026-09-02 批三验收：屏上写「待派 12」，而监视页同刻显示 待派=11 · 在途=1。
  // 12 是 待派+在途 的和，却挂着「待派」这个标签。同一块屏上两个数打架，
  // 而错的那个正是常驻在视野里的那个。PRODUCT 原则五要挡的就是这一步。
  const r = 产线文({ 在跑: [], 待派: 11, 在途: 1, 闸数: 0 }, 现在);
  assert.strictEqual(r.文, '零在跑 · 待跑 12');
  assert.ok(!/待派/.test(r.文), `实得「${r.文}」—— 「待派」是台账里的一个具体状态，不是这个和的名字`);
});

test('守⑧⑤ **零在跑、零待派、零在途，而闸上还压着东西 → 全卡在你**', () => {
  // 三版提案都漏了这一格。它和「产线空闲」在旧写法里长得一模一样，
  // 而这两件事对制作人的含义正好相反：一个是没事了，一个是**所有事都在等他**。
  const r = 产线文({ 在跑: [], 待派: 0, 在途: 0, 闸数: 61 }, 现在);
  assert.strictEqual(r.文, '零在跑 · 全卡在你', `实得「${r.文}」`);
  assert.strictEqual(r.级, '警');
});

test('守⑧⑥ 真的什么都没有才说空闲，且不报警', () => {
  const r = 产线文({ 在跑: [], 待派: 0, 在途: 0, 闸数: 0 }, 现在);
  assert.strictEqual(r.文, '产线空闲');
  assert.strictEqual(r.级, '弱');
});

test('守⑨ 第五态与第六态必须分得开（旧写法里它们都是「在跑 0」）', () => {
  const 卡 = 产线文({ 在跑: [], 待派: 0, 在途: 0, 闸数: 61 }, 现在);
  const 闲 = 产线文({ 在跑: [], 待派: 0, 在途: 0, 闸数: 0 }, 现在);
  assert.notStrictEqual(卡.文, 闲.文);
  assert.notStrictEqual(卡.级, 闲.级);
});

test('守⑩ 不报「停了多久」—— 那个数今天取不到（journal 当月 实弹开工 零条）', () => {
  for (const s of [{ 在跑: [], 待派: 0, 在途: 0, 闸数: 61 }, { 在跑: [], 待派: 0, 在途: 0, 闸数: 0 }]) {
    const 文 = 产线文(s, 现在).文;
    assert.ok(!/停\s*[\d.]|[\d.]\s*天/.test(文), `实得「${文}」—— 报了一个取不到的量`);
  }
});

test('守⑪ 龄文：一小时以内报分，超过报度分（与跑列同一把尺）', () => {
  assert.strictEqual(龄文(0), '0′');
  assert.strictEqual(龄文(59), '59′');
  assert.strictEqual(龄文(60), '1° 0′');
  assert.strictEqual(龄文(252), '4° 12′');
  assert.strictEqual(龄文(-5), '0′', '负数是钟不对，不是负的时长');
});
